'use strict';
const assert=require('node:assert/strict');
const R=require('../radar-analysis');
const {buildRadarAnalyticalInput,buildPortfolioAnalytics,scopedDataForSharedFilters}=require('../server');
const near=(a,b,message)=>assert(Math.abs(a-b)<1e-8,message||`${a} != ${b}`);
const unit=(id,price=8000,available=true)=>({id:String(id),priceM2:price,price:price*50,available});
const photo=(date,units)=>({date,id:date,units});
const constant=(date,price=8000)=>photo(date,[unit('same',price)]);
const months=Array.from({length:9},(_,i)=>({month:`2026-${String(i+1).padStart(2,'0')}`,value:1}));

assert.deepEqual(R.AXES,['vso','ivv','absorption','coverage','adjustment','iap']);
assert.equal(R.normalized(null,[0,2,4]),null);
assert.equal(R.normalized(2,[2]),50);
assert.equal(R.normalized(2,[2,2,2]),50);
assert.equal(R.normalized(2,[1,2,1000000]),50,'Outlier must not flatten the middle score.');
assert.equal(R.normalized(5,[5,18],true),100);
assert.equal(R.normalized(18,[5,18],true),0);
assert.equal(R.normalized(2,[1,2,2,3]),50,'Ties share a midrank.');
assert.equal(R.median([1,2,999]),2);
assert.equal(R.median([]),null);

// Net stock change between the first and last tables in the selected period.
const before=Array.from({length:20},(_,i)=>unit(i));
const after=before.filter(item=>Number(item.id)>=12);
let estimate=R.absorption([photo('2026-04-01',before),photo('2026-06-30',after)]);
near(estimate.value,12/90*30.44);assert.equal(estimate.absorbedUnits,12);assert.equal(estimate.observedDays,90);
assert.equal(estimate.initialStock,20);assert.equal(estimate.finalStock,8);
estimate=R.absorption([photo('2026-04-01',before),photo('2026-08-01',after)]);
assert.equal(estimate.observedDays,122);near(estimate.value,12/122*30.44);
assert(R.absorption([photo('2026-01-01',before),photo('2026-08-01',after)]).value>0,'Use the entire selected period, without an implicit 90/180-day truncation.');
assert.equal(R.absorption([photo('2026-04-01',before),photo('2026-06-30',before)]).value,0);
assert.equal(R.absorption([photo('2026-04-01',before),photo('2026-06-30',after)],'2026-06').value,null,'Two observations are required within the filter period.');
assert.equal(R.absorption([photo('2026-04-01',[unit(1)]),photo('2026-05-01',[unit(1,8000,false)])]).absorbedUnits,1);
const replenished=[photo('2026-04-01',[unit(1),unit(2)]),photo('2026-05-01',[unit(2),unit(3)])];
assert.equal(R.absorption(replenished).value,0,'New entries offset removed availability; do not sum gross exits.');
const growth=[photo('2026-04-01',[unit(1)]),photo('2026-05-01',[unit(1),unit(2)])];
assert(R.absorption(growth).value<0,'Preserve negative net movement as stock growth, not zero or sales.');
assert.equal(R.absorption([photo('2026-04-01',before)]).value,null);
assert.equal(R.absorption([photo('2026-04-01',before),{date:'2026-05-01'}]).value,null);
assert.equal(R.prepareHistory([constant('2026-01-01'),constant('2026-06-01'),constant('2026-07-01')],'2026-06').length,2);
assert.equal(R.prepareHistory([constant('2026-01-01'),constant('2026-01-01',9000)]).length,1);

// Compounded monthly index, no invented missing competencies.
near(R.accumulateIgpm(months,'2026-03-01','2026-06-01').value,(1.01**3-1)*100);
assert.equal(R.accumulateIgpm(months.slice(0,4),'2026-03-01','2026-06-01').value,null);
assert.deepEqual(R.accumulateIgpm(months.slice(0,4),'2026-03-01','2026-06-01').missing,['2026-05','2026-06']);
assert.equal(R.accumulateIgpm(months,'2026-03-01','2026-03-20').value,null);
const eventHistory=['01','03','05','07','09'].map(m=>constant(`2026-${m}-01`,m>='07'?8500:8000));
let adjustment=R.priceAdjustment(eventHistory,months);
assert.equal(adjustment.event.date,'2026-07-01','September unchanged table must preserve July event.');
near(adjustment.value,6.25);assert.equal(adjustment.from,'2026-01-01');assert.equal(adjustment.to,'2026-07-01');
const noEvent=[constant('2026-03-01'),constant('2026-06-01')];
adjustment=R.priceAdjustment(noEvent,months);
assert.equal(adjustment.value,0);assert.equal(adjustment.event,null);assert.equal(adjustment.monitoredSince,'2026-03-01');assert(adjustment.gap<0);
assert.equal(adjustment.from,'2026-03-01','Never infer premonitoring history.');
assert(R.priceAdjustment([constant('2026-03-01'),constant('2026-06-01',8800)],months).gap>0);
assert(R.priceAdjustment([constant('2026-03-01'),constant('2026-06-01',8040)],months).gap<0);
assert.equal(R.priceAdjustment([constant('2026-03-01')],months).value,null);
assert.equal(R.priceAdjustment([constant('2026-03-01'),photo('2026-06-01',[unit('other')])],months).value,null);
assert.equal(R.priceAdjustment([constant('2026-03-01'),photo('2026-04-01',[unit('other')]),constant('2026-05-01'),constant('2026-06-01')],months).value,null);
adjustment=R.priceAdjustment([constant('2026-03-01'),constant('2026-06-01',8800)],[]);
near(adjustment.value,10);assert.equal(adjustment.gap,null,'Known adjustment can coexist with missing IGP-M.');
const threePrices=[photo('2026-03-01',[unit(1),unit(2),unit(3)]),photo('2026-06-01',[unit(1,8080),unit(2,8080),unit(3,800000)])];
near(R.priceAdjustment(threePrices,months).value,1,'Repricing uses median, not outlier-sensitive mean.');
const totalFallback=[photo('2026-03-01',[{id:'u',available:true,price:100}]),photo('2026-06-01',[{id:'u',available:true,price:110}])];
near(R.priceAdjustment(totalFallback,months).value,10);assert.match(R.priceAdjustment(totalFallback,months).basis,/Preço total/);
const twice=[constant('2026-01-01'),constant('2026-03-01',8400),constant('2026-06-01',8820),constant('2026-07-01',8820)];
assert.equal(R.priceAdjustment(twice,months).from,'2026-03-01');

